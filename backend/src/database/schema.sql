-- as datas e horas ficam em texto ('AAAA-MM-DD', 'HH:MM') e os campos de sim ou não em 0 e 1,
-- no mesmo formato que o frontend já recebia do SQLite.
-- COLLATE "C" ordena e compara letra por letra, como o SQLite: assim a ordem dos nomes
-- e a busca por palavra não mudam de um servidor para outro.

CREATE TABLE usuarios (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome          TEXT    COLLATE "C" NOT NULL,
  email         TEXT    NOT NULL UNIQUE,
  senha_hash    TEXT    NOT NULL,
  telefone      TEXT,
  perfil        TEXT    NOT NULL CHECK (perfil IN ('usuario', 'voluntario')),
  pais_origem   TEXT,
  idiomas       TEXT    NOT NULL DEFAULT 'pt', -- separados por virgula: 'es,pt'
  foto          TEXT,
  cep           TEXT,               -- endereço, todo opcional; cep só com os 8 números
  rua           TEXT,
  numero        TEXT,
  complemento   TEXT,
  bairro        TEXT,
  cidade        TEXT,
  estado        TEXT,               -- sigla: 'SP'
  aceite_lgpd   INTEGER NOT NULL DEFAULT 0,
  criado_em     TEXT    NOT NULL DEFAULT to_char(now() AT TIME ZONE 'America/Sao_Paulo', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE areas (
  id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome  TEXT COLLATE "C" NOT NULL UNIQUE
);

CREATE TABLE voluntarios (
  id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id             INTEGER NOT NULL UNIQUE REFERENCES usuarios(id) ON DELETE CASCADE,
  area_id                INTEGER NOT NULL REFERENCES areas(id),
  registro_profissional  TEXT,              -- OAB, CRP, CRESS (professor nao precisa)
  idiomas                TEXT    COLLATE "C" NOT NULL,  -- separados por virgula: 'pt,es,ht'
  bio                    TEXT    COLLATE "C",
  ativo                  INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE servicos (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  voluntario_id  INTEGER NOT NULL REFERENCES voluntarios(id) ON DELETE CASCADE,
  titulo         TEXT    COLLATE "C" NOT NULL,
  descricao      TEXT    COLLATE "C" NOT NULL,
  duracao_min    INTEGER NOT NULL DEFAULT 45,
  ativo          INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE horarios (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  voluntario_id  INTEGER NOT NULL REFERENCES voluntarios(id) ON DELETE CASCADE,
  data           TEXT    COLLATE "C" NOT NULL,   -- 'AAAA-MM-DD'
  hora_inicio    TEXT    COLLATE "C" NOT NULL,   -- 'HH:MM'
  hora_fim       TEXT    COLLATE "C" NOT NULL,   -- 'HH:MM'
  status         TEXT    NOT NULL DEFAULT 'livre' CHECK (status IN ('livre', 'reservado'))
);

CREATE TABLE agendamentos (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  horario_id  INTEGER NOT NULL REFERENCES horarios(id) ON DELETE CASCADE,
  usuario_id  INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  servico_id  INTEGER NOT NULL REFERENCES servicos(id) ON DELETE CASCADE,
  descricao   TEXT    NOT NULL,
  status      TEXT    NOT NULL DEFAULT 'confirmado'
              CHECK (status IN ('confirmado', 'cancelado', 'realizado')),
  anotacao    TEXT,
  link_video        TEXT,            -- sala do Google Meet, quando o Google está configurado
  google_evento_id  TEXT,            -- evento na agenda do projeto, para remarcar e cancelar
  criado_em   TEXT    NOT NULL DEFAULT to_char(now() AT TIME ZONE 'America/Sao_Paulo', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE INDEX idx_horarios_voluntario_data ON horarios (voluntario_id, data);
CREATE INDEX idx_agendamentos_usuario ON agendamentos (usuario_id);

-- o Postgres não cria índice sozinho nas chaves estrangeiras: estes servem aos JOINs e ao ON DELETE CASCADE
CREATE INDEX idx_agendamentos_horario ON agendamentos (horario_id);
CREATE INDEX idx_agendamentos_servico ON agendamentos (servico_id);
CREATE INDEX idx_servicos_voluntario ON servicos (voluntario_id);
CREATE INDEX idx_voluntarios_area ON voluntarios (area_id);

-- a API entra no banco como dona das tabelas, e a RLS não vale para a dona. Ligada e sem nenhuma regra,
-- ela só fecha a API automática do Supabase (Data API), por onde quem tivesse a chave pública leria as tabelas
ALTER TABLE usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE areas ENABLE ROW LEVEL SECURITY;
ALTER TABLE voluntarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE servicos ENABLE ROW LEVEL SECURITY;
ALTER TABLE horarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE agendamentos ENABLE ROW LEVEL SECURITY;
